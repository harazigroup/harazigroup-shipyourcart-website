-- Ship Your Cart v7: import prices (shipping INTO Malaysia) — Aramex Inbound B 2026, all-in (fuel included).
-- Run once in Supabase → SQL Editor (after v6). Safe to re-run (replaces the Aramex inbound rates).

alter table public.carriers add column if not exists direction text not null default 'export';  -- 'export' from Malaysia, 'import' into Malaysia
alter table public.carrier_rates_over add column if not exists mode text not null default 'multiplier';  -- 'multiplier' = RM x total kg, 'add_half' = last price + RM per extra 0.5 kg

create or replace function public.price_for(p_carrier text, p_cc text, p_kg numeric)
returns numeric language plpgsql stable security definer set search_path = public as $$
declare c public.carriers; z text; p numeric; ov numeric; om text; top_kg numeric; top_p numeric;
begin
  if p_kg is null or p_kg <= 0 then return null; end if;
  select * into c from public.carriers where id = p_carrier and active;
  if not found or p_kg > c.max_kg then return null; end if;
  select zone into z from public.carrier_zones where carrier = p_carrier and country_code = upper(p_cc);
  if z is null then return null; end if;
  select price into p from public.carrier_rates
   where carrier = p_carrier and zone = z and max_kg >= p_kg order by max_kg limit 1;
  if p is null then
    select per_kg, mode into ov, om from public.carrier_rates_over
     where carrier = p_carrier and zone = z and from_kg < p_kg order by from_kg desc limit 1;
    if ov is null then return null; end if;
    if om = 'add_half' then
      select max_kg, price into top_kg, top_p from public.carrier_rates
       where carrier = p_carrier and zone = z order by max_kg desc limit 1;
      p := top_p + ceil((p_kg - top_kg) / 0.5) * ov;
    else
      p := ceil(p_kg) * ov;
    end if;
  end if;
  return ceil(p * (1 + c.fuel_pct / 100) * (1 + c.markup_pct / 100));
end $$;
revoke all on function public.price_for(text, text, numeric) from public, anon, authenticated;

-- export prices (from Malaysia): only export carriers
create or replace function public.quote(p_cc text, p_kg numeric)
returns table (carrier text, name text, name_ar text, name_ms text, transit_en text, transit_ar text, transit_ms text, price_rm numeric)
language sql stable security definer set search_path = public as $$
  select * from (
    select c.id, c.name, c.name_ar, c.name_ms, c.transit_en, c.transit_ar, c.transit_ms, public.price_for(c.id, p_cc, round(p_kg, 2)) as price_rm
      from public.carriers c where c.active and c.direction = 'export'
  ) q where q.price_rm is not null order by q.price_rm;
$$;
create or replace function public.quote_countries()
returns setof text language sql stable security definer set search_path = public as $$
  select distinct z.country_code from public.carrier_zones z
    join public.carriers c on c.id = z.carrier and c.active and c.direction = 'export'
   where exists (select 1 from public.carrier_rates r where r.carrier = z.carrier and r.zone = z.zone)
   order by 1;
$$;

-- import prices (into Malaysia): p_cc is the country it ships FROM
create or replace function public.quote_import(p_cc text, p_kg numeric)
returns table (carrier text, name text, name_ar text, name_ms text, transit_en text, transit_ar text, transit_ms text, price_rm numeric)
language sql stable security definer set search_path = public as $$
  select * from (
    select c.id, c.name, c.name_ar, c.name_ms, c.transit_en, c.transit_ar, c.transit_ms, public.price_for(c.id, p_cc, round(p_kg, 2)) as price_rm
      from public.carriers c where c.active and c.direction = 'import'
  ) q where q.price_rm is not null order by q.price_rm;
$$;
grant execute on function public.quote_import(text, numeric) to anon, authenticated;
create or replace function public.quote_import_countries()
returns setof text language sql stable security definer set search_path = public as $$
  select distinct z.country_code from public.carrier_zones z
    join public.carriers c on c.id = z.carrier and c.active and c.direction = 'import'
   where exists (select 1 from public.carrier_rates r where r.carrier = z.carrier and r.zone = z.zone)
   order by 1;
$$;
grant execute on function public.quote_import_countries() to anon, authenticated;

